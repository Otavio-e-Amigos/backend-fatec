CREATE TABLE aula_da_grade (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_grade_id     BIGINT NOT NULL,
    dia_semana              SMALLINT NOT NULL,
    hora_inicio             TIME NOT NULL,
    hora_fim                TIME NOT NULL,

    CONSTRAINT fk_aula_grade_disciplina_grade FOREIGN KEY (disciplina_grade_id) REFERENCES disciplina_da_grade (id) ON DELETE RESTRICT,

    CONSTRAINT ck_aula_horario CHECK (hora_fim > hora_inicio),
    CONSTRAINT ck_aula_dia_semana CHECK (dia_semana BETWEEN 1 AND 7)
);

CREATE INDEX idx_aula_disciplina_grade_id ON aula_da_grade (disciplina_grade_id);