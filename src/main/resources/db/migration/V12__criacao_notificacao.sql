-- Notificações internas do Appointer (exibidas somente dentro do sistema).
-- Cada linha pertence a um único usuário destinatário: notificações destinadas a um perfil
-- são "espalhadas" (uma linha por usuário), o que permite controlar leitura individualmente.
CREATE TABLE notificacao (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          BIGINT       NOT NULL,
    categoria           VARCHAR(30)  NOT NULL,
    tipo                VARCHAR(50)  NOT NULL,
    titulo              VARCHAR(150) NOT NULL,
    mensagem            VARCHAR(1000) NOT NULL,
    referencia_tipo     VARCHAR(50),
    referencia_id       BIGINT,
    lida                BOOLEAN      NOT NULL DEFAULT FALSE,
    lida_em             TIMESTAMP,
    pendente            BOOLEAN      NOT NULL DEFAULT FALSE,
    resolvida_em        TIMESTAMP,
    chave_deduplicacao  VARCHAR(120),
    expira_em           TIMESTAMP,
    created_at          TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT fk_notificacao_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT uk_notificacao_usuario_chave UNIQUE (usuario_id, chave_deduplicacao),
    CONSTRAINT ck_notificacao_categoria CHECK (categoria IN ('EXTRACAO_GRADE', 'FOLHA_PONTO', 'RELATORIO', 'CALENDARIO')),
    CONSTRAINT ck_notificacao_titulo CHECK (btrim(titulo) <> '')
);

CREATE INDEX idx_notificacao_usuario_created ON notificacao (usuario_id, created_at DESC);
CREATE INDEX idx_notificacao_usuario_nao_lida ON notificacao (usuario_id) WHERE lida = FALSE;
CREATE INDEX idx_notificacao_chave ON notificacao (chave_deduplicacao) WHERE chave_deduplicacao IS NOT NULL;
