-- Histórico de geração das folhas de ponto (DOCX oficial).
-- grade_id usa SET NULL para não impedir a exclusão de grades (regra existente); os dados do
-- período letivo ficam copiados (snapshot) para preservar o histórico.
CREATE TABLE registro_folha_ponto (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id             BIGINT      NOT NULL,
    grade_id                 BIGINT,
    usuario_id               BIGINT,
    mes                      SMALLINT    NOT NULL,
    ano                      INTEGER     NOT NULL,
    periodo_letivo_ano       INTEGER,
    periodo_letivo_semestre  SMALLINT,
    grade_outro_periodo      BOOLEAN     NOT NULL DEFAULT FALSE,
    dias_sem_aula            SMALLINT    NOT NULL DEFAULT 0,
    quantidade_disciplinas   SMALLINT    NOT NULL DEFAULT 0,
    formato                  VARCHAR(10) NOT NULL DEFAULT 'DOCX',
    created_at               TIMESTAMP   NOT NULL DEFAULT now(),

    CONSTRAINT fk_registro_folha_professor FOREIGN KEY (professor_id) REFERENCES professor (id) ON DELETE RESTRICT,
    CONSTRAINT fk_registro_folha_grade FOREIGN KEY (grade_id) REFERENCES grade (id) ON DELETE SET NULL,
    CONSTRAINT fk_registro_folha_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE SET NULL,
    CONSTRAINT ck_registro_folha_mes CHECK (mes BETWEEN 1 AND 12),
    CONSTRAINT ck_registro_folha_ano CHECK (ano BETWEEN 2000 AND 2050)
);

CREATE INDEX idx_registro_folha_created ON registro_folha_ponto (created_at);
CREATE INDEX idx_registro_folha_professor_created ON registro_folha_ponto (professor_id, created_at);
