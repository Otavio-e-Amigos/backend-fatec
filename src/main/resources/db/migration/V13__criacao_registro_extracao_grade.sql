-- Histórico das extrações de grade (PDF -> Gemini).
-- A extração continua sem gravar Grade/DisciplinaDaGrade/AulaDaGrade: aqui fica apenas o registro
-- do processamento, usado pelos relatórios e pelas notificações. O CPF extraído NÃO é armazenado.
CREATE TABLE registro_extracao_grade (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id              BIGINT,
    professor_id            BIGINT,
    nome_arquivo            VARCHAR(255),
    tamanho_bytes           BIGINT,
    status                  VARCHAR(30)  NOT NULL,
    mensagem_erro           VARCHAR(500),
    professor_nome          VARCHAR(150),
    professor_matricula     VARCHAR(20),
    semestre                SMALLINT,
    ano                     INTEGER,
    quantidade_disciplinas  INTEGER      NOT NULL DEFAULT 0,
    quantidade_aulas        INTEGER      NOT NULL DEFAULT 0,
    quantidade_avisos       INTEGER      NOT NULL DEFAULT 0,
    duracao_ms              BIGINT,
    created_at              TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT fk_registro_extracao_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE SET NULL,
    CONSTRAINT fk_registro_extracao_professor FOREIGN KEY (professor_id) REFERENCES professor (id) ON DELETE SET NULL,
    CONSTRAINT ck_registro_extracao_status CHECK (status IN ('SUCESSO', 'SUCESSO_COM_AVISOS', 'FALHA')),
    CONSTRAINT ck_registro_extracao_quantidades CHECK (quantidade_disciplinas >= 0 AND quantidade_aulas >= 0 AND quantidade_avisos >= 0)
);

CREATE INDEX idx_registro_extracao_created ON registro_extracao_grade (created_at);
