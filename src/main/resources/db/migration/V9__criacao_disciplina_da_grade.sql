CREATE TABLE disciplina_da_grade (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_id            BIGINT NOT NULL,
    disciplina_id       BIGINT NOT NULL,
    curso_id            BIGINT NOT NULL,
    semestre_curso      SMALLINT,
    periodo             VARCHAR(5),
    quantidade_aulas    SMALLINT NOT NULL,
    op                  INTEGER,
    status              VARCHAR(20) NOT NULL,
    created_at          TIMESTAMP NOT NULL DEFAULT now(),
    updated_at          TIMESTAMP NOT NULL DEFAULT now(),

    CONSTRAINT fk_disciplina_grade_grade FOREIGN KEY (grade_id) REFERENCES grade (id) ON DELETE RESTRICT,
    CONSTRAINT fk_disciplina_grade_disciplina FOREIGN KEY (disciplina_id) REFERENCES disciplina (id) ON DELETE RESTRICT,
    CONSTRAINT fk_disciplina_grade_curso FOREIGN KEY (curso_id) REFERENCES curso (id) ON DELETE RESTRICT,

    CONSTRAINT ck_disciplina_grade_qtd_aulas CHECK (quantidade_aulas > 0),

    CONSTRAINT ck_disciplina_grade_periodo CHECK (periodo IN ('MANHA', 'TARDE', 'NOITE') OR periodo IS NULL)
);

-- Índices para otimização de buscas relacionais
CREATE INDEX idx_disciplina_grade_grade_id ON disciplina_da_grade (grade_id);
CREATE INDEX idx_disciplina_grade_disciplina_id ON disciplina_da_grade (disciplina_id);
CREATE INDEX idx_disciplina_grade_curso_id ON disciplina_da_grade (curso_id);